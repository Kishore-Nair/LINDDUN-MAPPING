"""Layer 1 — exact, deterministic provenance for every LINDDUN label.

The LINDDUN label in corpus_final.parquet is a pure function of cwe_id:
verified directly against the corpus (grouping by cwe_id yields exactly one
label-set per CWE, for all 213,469 labelled rows). So the whole explanation
space is small — 102 CWEs carry a label — and a chain can be precomputed
once and looked up per row in O(1) rather than re-deriving per datapoint.

This module reconstructs, for any CWE:

    cwe_id -> category_cwe_id(s)   (hop 1, cwe_category_map.csv)
           -> LINDDUN class(es)    (hop 2, category_id_to_linddun.csv)

and records WHY a label is absent, which matters as much as why one is
present: 133,861 corpus rows carry a CWE but no LINDDUN class. There are
three distinct reasons, and they are not interchangeable.
"""

import csv
from collections import defaultdict
from dataclasses import dataclass, field

from . import paths


# Reasons a CWE ends up with no LINDDUN class. Kept as explicit constants
# because "no label" is a finding, not a gap to be silently filled.
NO_CWE = "no_cwe"                      # row has no CWE at all
EXCLUDED = "cwe_excluded"              # MITRE-discouraged/abstract, by decision
NO_CATEGORY = "cwe_has_no_category"    # CWE absent from hop 1
CATEGORY_UNMAPPED = "category_has_no_linddun"   # hop 1 ok, hop 2 empty
MAPPED = "mapped"


@dataclass
class CategoryStep:
    category_id: str
    category_name: str
    linddun: tuple = ()

    @property
    def contributed(self):
        return bool(self.linddun)


@dataclass
class Chain:
    """The full derivation for one CWE."""
    cwe_id: str
    status: str
    categories: list = field(default_factory=list)
    linddun: tuple = ()
    excluded_reason: str = ""
    category_added: str = ""

    @property
    def is_labelled(self):
        return self.status == MAPPED


def _read(path, required=True):
    if not path.exists():
        if required:
            raise SystemExit(
                f"{path} not found — run the pipeline through "
                f"04_apply_linddun.py first.")
        return []
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


class ChainIndex:
    """Precomputed CWE -> Chain for the whole taxonomy."""

    def __init__(self, overrides=None):
        self.cwe_to_cats = defaultdict(set)
        self.cat_name = {}
        self.added = {}
        for r in _read(paths.CWE_CATEGORY_MAP):
            cwe = r["cwe_id"].strip().upper()
            cid = r["category_cwe_id"].strip().upper()
            self.cwe_to_cats[cwe].add(cid)
            self.cat_name[cid] = r["category_name"].strip()

        # Hop-1 additions. cwe_category_map.csv is regenerated by 03c from
        # the raw MITRE extract, so a CWE missing from that extract cannot be
        # fixed by editing the generated file. These are merged in at load
        # time instead, which survives regeneration and keeps the addition
        # visible in the explanation rather than buried in a derived artefact.
        for r in _read(paths.CATEGORY_ADDITIONS, required=False):
            cwe = r["cwe_id"].strip().upper()
            cid = r["category_cwe_id"].strip().upper()
            self.cwe_to_cats[cwe].add(cid)
            self.cat_name.setdefault(cid, r["category_name"].strip())
            self.added[cwe] = r["basis"]

        self.cat_linddun = defaultdict(set)
        for r in _read(paths.CATEGORY_LINDDUN):
            ld = (r.get("linddun_category") or "").strip()
            if ld:
                self.cat_linddun[r["category_cwe_id"].strip().upper()].add(ld)

        self.excluded = {}
        for r in _read(paths.EXCLUDED_CWES, required=False):
            self.excluded[r["cwe_id"].strip().upper()] = (
                r.get("mitre_mapping_guidance") or r.get("verification_status")
                or "excluded")

        self.overrides = overrides
        self._cache = {}

    # -----------------------------------------------------------------
    def chain(self, cwe_id):
        """Return the Chain for a CWE, deriving it once and caching."""
        # Guard on TYPE, not truthiness. pandas >= 3 infers StringDtype for
        # a text column, whose missing value is NaN rather than None; NaN is
        # truthy, so `if not cwe_id` lets it through and str(NaN) becomes the
        # literal "NAN", which then reports as cwe_has_no_category instead of
        # no_cwe. Measured: that mislabelled 55,550 NVD-CWE-Other rows.
        if not isinstance(cwe_id, str) or not cwe_id.strip():
            return Chain(cwe_id="", status=NO_CWE)
        cwe = str(cwe_id).strip().upper()
        if cwe in self._cache:
            return self._cache[cwe]

        if cwe in self.excluded:
            c = Chain(cwe, EXCLUDED, excluded_reason=self.excluded[cwe])
            self._cache[cwe] = c
            return c

        cats = sorted(self.cwe_to_cats.get(cwe, ()))
        if not cats:
            c = Chain(cwe, NO_CATEGORY)
            self._cache[cwe] = c
            return c

        steps, union = [], set()
        for cid in cats:
            ld = tuple(sorted(self.cat_linddun.get(cid, ())))
            steps.append(CategoryStep(cid, self.cat_name.get(cid, "?"), ld))
            union |= set(ld)

        status = MAPPED if union else CATEGORY_UNMAPPED
        c = Chain(cwe, status, steps, tuple(sorted(union)),
                  category_added=self.added.get(cwe, ""))
        self._cache[cwe] = c
        return c

    def all_labelled_cwes(self):
        return sorted(c for c in self.cwe_to_cats
                      if self.chain(c).is_labelled)
